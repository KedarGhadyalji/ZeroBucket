// ---- error classification ----------------------------------------------------------------------

const RETRYABLE_ERRNOS = new Set([
  1205, // ER_LOCK_WAIT_TIMEOUT
  1213, // ER_LOCK_DEADLOCK
  1040, // ER_CON_COUNT_ERROR (too many connections)
  1053, // ER_SERVER_SHUTDOWN
  1927, // ER_CONNECTION_KILLED (MariaDB)
  2002, // CR_CONNECTION_ERROR
  2003, // CR_CONN_HOST_ERROR
  2006, // CR_SERVER_GONE_ERROR
  2013, // CR_SERVER_LOST
]);
const CONNECTION_CODES = new Set([
  "PROTOCOL_CONNECTION_LOST",
  "PROTOCOL_ENQUEUE_AFTER_FATAL_ERROR",
  "PROTOCOL_ENQUEUE_AFTER_QUIT",
  "ECONNRESET",
  "ECONNREFUSED",
  "ETIMEDOUT",
  "EPIPE",
  "ECONNABORTED",
]);

interface MysqlError {
  code?: unknown;
  errno?: unknown;
  fatal?: unknown;
}

function errnoOf(exc: unknown): number | undefined {
  const n = (exc as MysqlError | null)?.errno;
  return typeof n === "number" ? n : undefined;
}

/** Thrown when waiting for a pool slot times out. Not retryable: retrying would just wait again. */
class PoolTimeoutError extends StorageError {}

/** Transient (worth retrying) vs. permanent (fails identically every time). */
export function isRetryable(exc: unknown): boolean {
  if (!(exc instanceof Error) || exc instanceof PoolTimeoutError) return false;
  const e = exc as MysqlError;
  const n = errnoOf(exc);
  if (n !== undefined && RETRYABLE_ERRNOS.has(n)) return true;
  if (typeof e.code === "string") {
    if (CONNECTION_CODES.has(e.code)) return true;
    if (
      e.code === "ER_LOCK_WAIT_TIMEOUT" ||
      e.code === "ER_LOCK_DEADLOCK" ||
      e.code === "ER_CON_COUNT_ERROR" ||
      e.code === "ER_SERVER_SHUTDOWN" ||
      e.code === "ER_CONNECTION_KILLED"
    )
      return true;
  }
  return false;
}

/** Errors after which the pooled connection must be destroyed, not returned to the pool. */
function isConnectionLevel(exc: unknown): boolean {
  if (!(exc instanceof Error)) return false;
  const e = exc as MysqlError;
  if (e.fatal === true) return true;
  if (typeof e.code === "string" && CONNECTION_CODES.has(e.code)) return true;
  const n = errnoOf(exc);
  return n === 2006 || n === 2013 || n === 1927 || n === 1053;
}

const MAX_BACKOFF_MS = 2000;

export function backoffDelayMs(attempt: number, baseDelayMs: number): number {
  const exponential = baseDelayMs * 2 ** (attempt - 1);
  const jitter = Math.random() * baseDelayMs;
  return Math.min(exponential + jitter, MAX_BACKOFF_MS);
}

/** Turn the one error users hit in practice into an actionable message; everything else passes through wrap(). */
function friendly(prefix: string, exc: unknown): StorageError {
  if (errnoOf(exc) === 1153) {
    return new StorageError(
      `${prefix}: the image is larger than the server's max_allowed_packet. Raise it (for example \`SET GLOBAL max_allowed_packet = 67108864\`, ` +
        `and set it in my.cnf to make it permanent), or lower \`maxBytes\`.`,
      { cause: exc },
    );
  }
  return wrap(prefix, exc);
}

/** Naive UTC `YYYY-MM-DD HH:MM:SS.ffffff`, the format of the Python package's DATETIME(6) values. */
function mysqlNow(): string {
  return `${new Date().toISOString().replace("T", " ").replace("Z", "")}000`;
}

function normalizeUrl(url: string): string {
  return url.replace(/^mariadb:\/\//i, "mysql://");
}

function isMysqlConnection(c: Connection): c is MysqlQueryable {
  const m = c as Partial<MysqlQueryable>;
  return typeof m.query === "function" && typeof m.execute === "function";
}

export interface MySQLBackendOptions {
  /** `mysql://user:password@host:3306/database` (`mariadb://` is accepted too). Required unless `pool` is given. */
  connectionString?: string;
  /** Bring your own `mysql2/promise` Pool (not closed by `close()`). Pool sizing options are then ignored. */
  pool?: MysqlPoolLike;
  /** Create the schema on first use. Default true. */
  autoMigrate?: boolean;
  /** Retries for transient errors on pooled calls. Default 3; 0 disables. */
  maxRetries?: number;
  /** Base for exponential backoff with jitter (capped at 2s). Default 100. */
  retryBaseDelayMs?: number;
  /** Accepted for parity with the other backends. mysql2 opens connections on demand, so there is no minimum to hold. */
  poolMinSize?: number;
  /** Maximum simultaneous connections. Default 5. */
  poolMaxSize?: number;
  /** Max wait for a pooled connection (also the TCP connect timeout). Default 10000. */
  poolTimeoutMs?: number;
  onOperation?: (event: OperationEvent) => void;
  /** Enables transparent reads of tiered rows and `tierToObjectStorage()`. */
  objectStorage?: ObjectStorageLike;
  /** Not available for MySQL yet; passing `true` throws. */
  dedup?: boolean;
}

type Work<T> = (q: MysqlQueryable) => Promise<T>;

export class MySQLBackend implements StorageBackend {
  private pool: MysqlPoolLike | undefined;
  private readonly ownsPool: boolean;
  private readyPromise: Promise<void> | undefined;
  private closed = false;
  private readonly maxRetries: number;
  private readonly retryBaseDelayMs: number;
  private readonly poolTimeoutMs: number;
  private readonly autoMigrate: boolean;

  constructor(private readonly opts: MySQLBackendOptions) {
    if (!opts.connectionString && !opts.pool) {
      throw new TypeError(
        "MySQLBackend requires either `connectionString` or `pool`",
      );
    }
    if (opts.dedup) {
      throw new TypeError(
        "dedup mode is not available for MySQL in the npm package yet (the Python package supports it). " +
          "Use classic mode, or Postgres/SQLite for dedup.",
      );
    }
    this.ownsPool = !opts.pool;
    this.pool = opts.pool;
    this.maxRetries = opts.maxRetries ?? 3;
    this.retryBaseDelayMs = opts.retryBaseDelayMs ?? 100;
    this.poolTimeoutMs = opts.poolTimeoutMs ?? 10_000;
    this.autoMigrate = opts.autoMigrate ?? true;
  }

  // ---- lifecycle -------------------------------------------------------

  ready(): Promise<void> {
    if (this.closed)
      return Promise.reject(
        new StorageError("This ZeroBucket instance has been closed"),
      );
    this.readyPromise ??= this.init().catch((exc) => {
      this.readyPromise = undefined; // allow a later attempt (e.g. the database was briefly down)
      throw exc;
    });
    return this.readyPromise;
  }

  private async init(): Promise<void> {
    if (!this.pool) {
      let mod: {
        createPool(config: Record<string, unknown>): MysqlPoolLike;
        default?: {
          createPool(config: Record<string, unknown>): MysqlPoolLike;
        };
      };
      try {
        mod = (await import("mysql2/promise")) as unknown as typeof mod;
      } catch (cause) {
        throw new StorageError(
          "MySQLBackend requires the 'mysql2' package. Install it with: npm install mysql2",
          { cause },
        );
      }
      const createPool = (mod.default ?? mod).createPool;
      this.pool = createPool({
        uri: normalizeUrl(this.opts.connectionString!),
        connectionLimit: this.opts.poolMaxSize ?? 5,
        waitForConnections: true,
        queueLimit: 0,
        connectTimeout: this.poolTimeoutMs,
        charset: "utf8mb4",
        timezone: "Z",
        enableKeepAlive: true,
      });
    }
    try {
      if (this.autoMigrate) {
        await this.runPooled("migrate", (q) => this.migrate(q), false);
      } else {
        await this.runPooled("ping", (q) => q.query("SELECT 1"), false);
      }
    } catch (exc) {
      if (this.ownsPool) {
        await this.pool.end().catch(() => {});
        this.pool = undefined;
      }
      throw exc instanceof StorageError
        ? exc
        : new StorageError(`Could not connect to MySQL/MariaDB: ${msg(exc)}`, {
            cause: exc,
          });
    }
  }

  /**
   * Create the schema if missing, under a server-side named lock so concurrent first callers (in this
   * or any other process) run the DDL one at a time. Every step checks before it changes anything, so
   * re-running is a no-op.
   */
  private async migrate(q: MysqlQueryable): Promise<void> {
    const locked = (
      (await q.query("SELECT GET_LOCK(?, 30) AS got", [MIGRATE_LOCK]))[0] as {
        got: number | null;
      }[]
    )[0]?.got;
    if (locked !== 1) {
      throw new StorageError(
        "Timed out waiting for another process to finish migrating the ZeroBucket schema.",
      );
    }
    try {
      // DDL only when something is actually missing. Even a no-op ALTER TABLE needs an EXCLUSIVE metadata
      // lock, which waits behind every open transaction on the table, and while it waits, every other
      // query on that table queues behind IT. Starting an app instance during a long transaction must
      // not be able to stall all traffic, so a current schema issues no DDL at all.
      const tableExists =
        (
          (
            await q.query(
              "SELECT 1 FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'zerobucket_images'",
            )
          )[0] as unknown[]
        ).length > 0;
      if (!tableExists) await q.query(SCHEMA);
      const cols = new Map(
        (
          (
            await q.query(
              "SELECT COLUMN_NAME AS c, IS_NULLABLE AS nullable FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'zerobucket_images'",
            )
          )[0] as { c: string; nullable: string }[]
        ).map((r) => [r.c, r.nullable]),
      );
      if (!cols.has("storage_backend"))
        await q.query(
          `ALTER TABLE zerobucket_images ADD COLUMN storage_backend VARCHAR(20) NOT NULL DEFAULT '${LOCAL}'`,
        );
      if (!cols.has("object_storage_bucket"))
        await q.query(
          "ALTER TABLE zerobucket_images ADD COLUMN object_storage_bucket VARCHAR(255)",
        );
      if (!cols.has("object_storage_key"))
        await q.query(
          "ALTER TABLE zerobucket_images ADD COLUMN object_storage_key VARCHAR(512)",
        );
      if (cols.get("data") === "NO")
        await q.query(
          "ALTER TABLE zerobucket_images MODIFY data LONGBLOB NULL",
        );
      const hasCheck =
        (
          (
            await q.query(
              "SELECT 1 FROM information_schema.TABLE_CONSTRAINTS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'zerobucket_images' AND CONSTRAINT_NAME = ?",
              [TIERING_CHECK],
            )
          )[0] as unknown[]
        ).length > 0;
      if (!hasCheck) {
        await q.query(
          `ALTER TABLE zerobucket_images ADD CONSTRAINT ${TIERING_CHECK} CHECK (` +
            `(storage_backend = '${LOCAL}' AND data IS NOT NULL AND object_storage_bucket IS NULL AND object_storage_key IS NULL) OR ` +
            `(storage_backend = 'object_storage' AND data IS NULL AND object_storage_bucket IS NOT NULL AND object_storage_key IS NOT NULL))`,
        );
      }
    } catch (exc) {
      throw new StorageError(`Migration failed: ${msg(exc)}`, { cause: exc });
    } finally {
      await q.query("SELECT RELEASE_LOCK(?)", [MIGRATE_LOCK]).catch(() => {});
    }
  }

  async close(): Promise<void> {
    this.closed = true;
    const pool = this.pool;
    this.pool = undefined;
    this.readyPromise = undefined;
    if (pool && this.ownsPool) await pool.end();
  }

  // ---- execution core --------------------------------------------------

  private emit(
    operation: string,
    start: number,
    success: boolean,
    error: string | null,
    retryCount: number,
  ): void {
    const cb = this.opts.onOperation;
    if (!cb) return;
    try {
      cb({
        operation,
        durationMs: performance.now() - start,
        success,
        error,
        retryCount,
      });
    } catch {
      // A bug in a metrics callback must never break a real operation.
    }
  }

  /** Wait for a pool slot, but never longer than poolTimeoutMs. */
  private acquire(): Promise<MysqlPoolConnectionLike> {
    const pool = this.pool;
    if (this.closed || !pool)
      return Promise.reject(
        new StorageError("This ZeroBucket instance has been closed"),
      );
    return new Promise((resolve, reject) => {
      let settled = false;
      const timer = setTimeout(() => {
        settled = true;
        reject(
          new PoolTimeoutError(
            `Timed out after ${this.poolTimeoutMs}ms waiting for a MySQL/MariaDB connection ` +
              `(poolMaxSize=${this.opts.poolMaxSize ?? 5}; all connections are in use).`,
          ),
        );
      }, this.poolTimeoutMs);
      pool.getConnection().then(
        (conn) => {
          if (settled) {
            conn.release(); // arrived after we gave up: hand it straight back
            return;
          }
          settled = true;
          clearTimeout(timer);
          resolve(conn);
        },
        (exc) => {
          if (settled) return;
          settled = true;
          clearTimeout(timer);
          reject(exc);
        },
      );
    });
  }

  /**
   * Run `work` on a pooled connection. `tx` wraps it in a transaction. Transient failures retry the
   * WHOLE closure on a fresh connection after a full rollback.
   */
  private async runPooled<T>(
    operation: string,
    work: Work<T>,
    tx: boolean,
  ): Promise<T> {
    const start = performance.now();
    let attempt = 0;
    for (;;) {
      let conn: MysqlPoolConnectionLike | undefined;
      let destroy = false;
      try {
        conn = await this.acquire();
        if (tx) await conn.beginTransaction();
        const result = await work(conn);
        if (tx) await conn.commit();
        this.emit(operation, start, true, null, attempt);
        return result;
      } catch (exc) {
        if (conn && tx) {
          try {
            await conn.rollback();
          } catch {
            destroy = true; // cannot trust a connection that cannot roll back
          }
        }
        if (isConnectionLevel(exc)) destroy = true;
        attempt += 1;
        if (attempt > this.maxRetries || !isRetryable(exc)) {
          this.emit(operation, start, false, msg(exc), attempt - 1);
          throw exc;
        }
      } finally {
        if (conn) {
          if (destroy) conn.destroy();
          else conn.release();
        }
      }
      await sleep(backoffDelayMs(attempt, this.retryBaseDelayMs));
    }
  }

  /**
   * Run `work` and return its result, emitting exactly one OperationEvent.
   *
   * connection given  -> run once on it; no retry, and no commit/rollback of the caller's transaction.
   * connection absent -> pooled, retried (see runPooled).
   */
  private async run<T>(
    operation: string,
    connection: Connection | undefined,
    work: Work<T>,
    { tx = false }: { tx?: boolean } = {},
  ): Promise<T> {
    if (connection) {
      if (!isMysqlConnection(connection)) {
        throw new TypeError(
          "MySQLBackend expects a mysql2/promise connection as `connection` (an object with query() and execute()).",
        );
      }
      const start = performance.now();
      try {
        const result = tx
          ? await this.atomic(connection, work)
          : await work(connection);
        this.emit(operation, start, true, null, 0);
        return result;
      } catch (exc) {
        this.emit(operation, start, false, msg(exc), 0);
        throw exc;
      }
    }
    await this.ready();
    return this.runPooled(operation, work, tx);
  }

  /**
   * Make multi-statement work all-or-nothing on a CALLER-supplied connection.
   *
   * Is a transaction open? SAVEPOINT followed by ROLLBACK TO SAVEPOINT succeeds only inside one (in
   * autocommit mode the savepoint is gone before the next statement and the rollback fails with 1305).
   *  - Open  -> reuse that SAVEPOINT: a failure undoes only our work; success joins the caller's transaction.
   *  - None  -> START TRANSACTION and COMMIT our own, so a failure can never leave half-applied state.
   */
  private async atomic<T>(conn: MysqlQueryable, work: Work<T>): Promise<T> {
    let inTransaction: boolean;
    await conn.query("SAVEPOINT zerobucket_atomic");
    try {
      await conn.query("ROLLBACK TO SAVEPOINT zerobucket_atomic");
      inTransaction = true;
    } catch (exc) {
      if (errnoOf(exc) !== 1305) throw exc; // ER_SP_DOES_NOT_EXIST: no open transaction
      inTransaction = false;
      await conn.query("START TRANSACTION");
    }
    try {
      const result = await work(conn);
      await conn.query(
        inTransaction ? "RELEASE SAVEPOINT zerobucket_atomic" : "COMMIT",
      );
      return result;
    } catch (exc) {
      try {
        await conn.query(
          inTransaction
            ? "ROLLBACK TO SAVEPOINT zerobucket_atomic"
            : "ROLLBACK",
        );
        if (inTransaction)
          await conn.query("RELEASE SAVEPOINT zerobucket_atomic");
      } catch {
        // keep the original error
      }
      throw exc;
    }
  }

  // ---- StorageBackend --------------------------------------------------

  async put(
    row: PreparedRow,
    { connection }: CallOptions = {},
  ): Promise<string> {
    try {
      const id = randomUUID();
      await this.run("put", connection, async (q) => {
        await q.execute(INSERT, rowParams(id, row, mysqlNow()));
      });
      return id;
    } catch (exc) {
      throw friendly("Failed to store image", exc);
    }
  }

  async putMany(
    rows: PreparedRow[],
    { connection }: CallOptions = {},
  ): Promise<string[]> {
    if (rows.length === 0) return [];
    try {
      // Ids are minted before the transaction, so a retry after a full rollback re-inserts the same
      // ids and can never create duplicates. One INSERT at a time keeps every packet one image big.
      const ids = rows.map(() => randomUUID());
      await this.run(
        "put_many",
        connection,
        async (q) => {
          const now = mysqlNow();
          for (let i = 0; i < rows.length; i++)
            await q.execute(INSERT, rowParams(ids[i]!, rows[i]!, now));
        },
        { tx: true },
      );
      return ids;
    } catch (exc) {
      throw friendly("Failed to store image batch", exc);
    }
  }

  async get(
    id: string,
    { connection }: CallOptions = {},
  ): Promise<StoredRecord | null> {
    if (!isValidId(id)) return null;
    let row: any;
    try {
      row = await this.run(
        "get",
        connection,
        async (q) => (await q.query(SELECT_FULL, [id]))[0][0],
      );
    } catch (exc) {
      throw wrap("Failed to retrieve image", exc);
    }
    return row ? this.hydrate(row, id) : null;
  }

  async getMany(
    ids: string[],
    { connection }: CallOptions = {},
  ): Promise<StoredRecord[]> {
    const valid = ids.filter(isValidId);
    if (valid.length === 0) return [];
    let rows: any[];
    try {
      rows = await this.run(
        "get_many",
        connection,
        async (q) => (await q.query(SELECT_MANY, [valid]))[0],
      );
    } catch (exc) {
      throw wrap("Failed to retrieve image batch", exc);
    }
    return mapLimit(rows, 4, (r) => this.hydrate(r, String(r.id)));
  }

  async getMetadata(
    id: string,
    { connection }: CallOptions = {},
  ): Promise<StoredRecordMetadata | null> {
    if (!isValidId(id)) return null;
    let row: any;
    try {
      row = await this.run(
        "get_metadata",
        connection,
        async (q) => (await q.query(SELECT_METADATA, [id]))[0][0],
      );
    } catch (exc) {
      throw wrap("Failed to retrieve image metadata", exc);
    }
    if (!row) return null;
    return {
      id: String(row.id),
      mimeType: row.mime_type,
      originalFilename: row.original_filename,
      sizeBytes: row.size_bytes,
      width: row.width,
      height: row.height,
      checksumSha256: row.checksum_sha256,
    };
  }

  async getStream(
    id: string,
    opts: StreamOptions,
  ): Promise<AsyncIterable<Buffer> | null> {
    if (!isValidId(id)) return null;
    const { connection, chunkSize } = opts;
    if (!Number.isInteger(chunkSize) || chunkSize <= 0)
      throw new RangeError("chunkSize must be a positive integer");

    let info: any;
    try {
      info = await this.run(
        "get_metadata",
        connection,
        async (q) => (await q.query(STREAM_INFO, [id]))[0][0],
      );
    } catch (exc) {
      throw wrap("Failed to retrieve image metadata", exc);
    }
    if (!info) return null;
    const totalSize: number = info.size_bytes;
    const start = opts.range?.start ?? 0;
    const end = Math.min(opts.range?.end ?? totalSize - 1, totalSize - 1); // inclusive, clamped

    if (info.storage_backend === "object_storage") {
      const os = this.opts.objectStorage;
      if (!os) throw tieredWithoutStorage(id, info.object_storage_key);
      return streamFromObjectStorage(
        os,
        id,
        info.object_storage_key,
        start,
        end,
        chunkSize,
      );
    }
    const self = this;

    async function* generate(): AsyncGenerator<Buffer> {
      let offset = start; // 0-based
      let delivered = 0;
      const wanted = Math.max(0, end - start + 1);
      while (delivered < wanted) {
        const length = Math.min(chunkSize, wanted - delivered);
        let row: any;
        try {
          row = await self.run(
            "get_stream",
            connection,
            async (q) => (await q.query(CHUNK, [offset + 1, length, id]))[0][0],
          );
        } catch (exc) {
          throw wrap("Failed to stream image", exc);
        }
        if (!row) {
          throw new StorageError(
            `Image ${JSON.stringify(id)} was deleted while streaming (delivered ${delivered} of ${wanted} bytes). ` +
              "Pass connection with your own open transaction if you need a consistent read across concurrent writers.",
          );
        }
        const chunk: Buffer | null = row.chunk;
        if (!chunk || chunk.length === 0) {
          throw new StorageError(
            `Image ${JSON.stringify(id)} ended early while streaming (delivered ${delivered} of ${wanted} bytes).`,
          );
        }
        yield chunk;
        offset += chunk.length;
        delivered += chunk.length;
      }
    }
    return generate();
  }

  async delete(id: string, { connection }: CallOptions = {}): Promise<boolean> {
    if (!isValidId(id)) return false;
    try {
      // No RETURNING: lock the row, learn where its bytes live, delete it, all in one transaction.
      const row = await this.run(
        "delete",
        connection,
        async (q) => {
          const found = (await q.query(LOCK_ONE, [id]))[0][0];
          if (!found) return undefined;
          await q.query(DELETE_ONE, [id]);
          return found;
        },
        { tx: true },
      );
      if (row?.storage_backend === "object_storage")
        await this.cleanupObject([row.object_storage_key], connection);
      return row !== undefined;
    } catch (exc) {
      throw wrap("Failed to delete image", exc);
    }
  }

  async deleteMany(
    ids: string[],
    { connection }: CallOptions = {},
  ): Promise<string[]> {
    const valid = [...new Set(ids.filter(isValidId))];
    if (valid.length === 0) return [];
    try {
      const rows: any[] = await this.run(
        "delete_many",
        connection,
        async (q) => {
          const found = (await q.query(LOCK_MANY, [valid]))[0] as any[];
          if (found.length === 0) return [];
          await q.query(DELETE_MANY, [found.map((r) => r.id)]);
          return found;
        },
        { tx: true },
      );
      await this.cleanupObject(
        rows
          .filter((r) => r.storage_backend === "object_storage")
          .map((r) => r.object_storage_key as string),
        connection,
      );
      return rows.map((r) => String(r.id));
    } catch (exc) {
      throw wrap("Failed to delete image batch", exc);
    }
  }

  async exists(id: string, { connection }: CallOptions = {}): Promise<boolean> {
    if (!isValidId(id)) return false;
    try {
      return await this.run(
        "exists",
        connection,
        async (q) => (await q.query(EXISTS, [id]))[0].length > 0,
      );
    } catch (exc) {
      throw wrap("Failed to check image existence", exc);
    }
  }

  // ---- helpers ---------------------------------------------------------

  private hydrate(row: any, id: string): Promise<StoredRecord> {
    return hydrateRow(row, id, this.opts.objectStorage);
  }

  /**
   * Remove tiered objects AFTER their rows are gone: once the row is deleted the image is correctly
   * "not found" to everyone, so a failed object delete only leaves a harmless orphan, whereas deleting
   * the object first and then failing the row delete would leave a row pointing at nothing.
   *
   * Never runs inside a caller-owned transaction (`connection`): we cannot know whether it will
   * commit. In that case the object stays until you remove it yourself after committing. Failures are
   * reported through onOperation and never fail the delete itself.
   */
  private async cleanupObject(
    keys: string[],
    connection: Connection | undefined,
  ): Promise<void> {
    const os = this.opts.objectStorage;
    if (!os || connection || keys.length === 0) return;
    await Promise.all(
      keys.map(async (key) => {
        const start = performance.now();
        try {
          await os.delete(key);
          this.emit("object_storage_delete", start, true, null, 0);
        } catch (exc) {
          this.emit("object_storage_delete", start, false, msg(exc), 0);
        }
      }),
    );
  }

  /**
   * Move an image's bytes out of the database into object storage, replacing the row's `data` with a
   * pointer. Returns null (no such image), false (already tiered: a safe no-op, so backfills can be
   * re-run) or true (tiered just now).
   *
   * SAFETY: the upload happens INSIDE the same transaction as the row lock (SELECT ... FOR UPDATE)
   * and the UPDATE that flips the row. If the upload fails the transaction rolls back and the row is
   * untouched: there is no moment when the bytes exist nowhere, or when a row claims to be tiered
   * without a completed upload.
   *
   * TRADEOFF: InnoDB row-locks only THIS row for the duration of the upload. Concurrent writes to this
   * image wait (up to innodb_lock_wait_timeout, 50s by default); every other row is unaffected and
   * plain reads are never blocked. Meant for explicit maintenance, not hot paths.
   *
   * Retry is safe: a transient error replays the whole closure, and the deterministic key (the image
   * id) makes the re-upload an idempotent overwrite.
   */
  async tierToObjectStorage(
    id: string,
    { connection }: CallOptions = {},
  ): Promise<boolean | null> {
    const os = this.opts.objectStorage;
    if (!os) {
      throw new StorageError(
        "tierToObjectStorage() requires objectStorage to be configured (new ZeroBucket({ objectStorage: new ObjectStorage({ bucket }) })).",
      );
    }
    if (!isValidId(id)) return null;
    const key = id.toLowerCase();
    try {
      return await this.run(
        "tier_to_object_storage",
        connection,
        async (q) => {
          const row = (await q.query(SELECT_FOR_TIERING, [id]))[0][0];
          if (!row) return null;
          if (row.storage_backend !== LOCAL) return false;
          await os.upload(key, row.data as Buffer, { mimeType: row.mime_type });
          await q.query(UPDATE_AFTER_TIERING, [os.bucket, key, mysqlNow(), id]);
          return true;
        },
        { tx: true },
      );
    } catch (exc) {
      throw wrap("Failed to tier image to object storage", exc);
    }
  }
}

