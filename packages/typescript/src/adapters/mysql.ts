/**
 * MySQL / MariaDB storage adapter (classic mode, streaming, object-storage tiering).
 *
 * Uses the EXACT schema the Python package's MySQLBackend creates (CHAR(36) ids, LONGBLOB data,
 * naive-UTC DATETIME(6) timestamps, storage_backend = 'mysql', the same CHECK constraint), so a Node
 * app and a Python app can share one database and read each other's rows.
 *
 * Decisions that differ from the Postgres adapter, each verified against a real MariaDB 10.11:
 *
 *  - NO `RETURNING`. MySQL 8.0 has none (MariaDB 10.5+ does, but one code path must serve both).
 *    delete()/deleteMany() therefore run `SELECT ... FOR UPDATE` and then `DELETE` inside ONE
 *    transaction, which also tells us which rows were tiered (so their objects can be cleaned up).
 *  - ids are generated by the application (`crypto.randomUUID()`), exactly like SQLite and Python.
 *  - Timestamps are written as pre-formatted UTC strings, never as JS Dates, so the result does not
 *    depend on the server's or the process's timezone setting.
 *  - Blobs travel through `execute()` (binary protocol, raw bytes). `query()` would inline a blob
 *    as a hex literal (2x the size, and the whole statement counts against max_allowed_packet).
 *    Everything else uses `query()`: with `execute()`, JS numbers are sent as DOUBLE, which MySQL
 *    8.0.22+ rejects in places like LIMIT and offsets, and SUBSTRING() offsets are such a place.
 *  - mysql2's pool has no acquire timeout, so `poolTimeoutMs` is implemented here. A waiter that
 *    times out is removed in effect: if its connection arrives late it is released straight back.
 *  - Retry re-runs the WHOLE unit of work on a fresh connection after a full ROLLBACK, never a single
 *    statement (the Python package hit exactly that "half-applied put" hazard with DBUtils).
 *    Connection loss, lock-wait timeout (1205) and deadlock (1213) are retried; the pool-timeout
 *    error is NOT (retrying would multiply the wait).
 *  - A caller-supplied `connection` (your own mysql2 connection) is never committed, rolled back or
 *    retried. For multi-statement work on it we first probe whether a transaction is open
 *    (SAVEPOINT + ROLLBACK TO fails with 1305 when none is): inside one we use a SAVEPOINT so a
 *    failure undoes only our work; outside one (autocommit) we open and commit our own.
 *  - Migration runs under `GET_LOCK()` so N processes starting at once do not race on the DDL, and it
 *    issues NO DDL when the schema is already current: even a no-op ALTER TABLE needs an exclusive
 *    metadata lock, which queues behind every open transaction and blocks all later queries on the table.
 *    (The Python package always runs `ALTER TABLE ... MODIFY data` at startup; both additions are
 *    purely additive and work on MySQL and MariaDB.)
 *  - Dedup mode (`dedup: true`) uses the Python package's two tables (zerobucket_blobs: one row per distinct
 *    content with a ref_count; zerobucket_image_refs: one row per image). A batch groups identical images,
 *    upserts each distinct blob ONCE in sorted checksum order and decrements in sorted order too: a global
 *    lock order, so two overlapping batches can never deadlock on each other's blob rows. Without `RETURNING`
 *    the decrement is `UPDATE ... ref_count = ref_count - n` (which takes the row lock) followed by a point
 *    `DELETE ... WHERE ref_count <= 0`; the foreign key makes deleting a still-referenced blob impossible.
 *  - Batch deletes lock with one `SELECT ... FOR UPDATE` and then use POINT statements, never `DELETE ... IN (...)`.
 *    On MariaDB 10.11 that statement is planned as a full scan on a small table (EXPLAIN type=ALL) while the ordered
 *    SELECT gets a range plan; a scan locks every row it passes, so overlapping batches deadlocked (measured: 126 per
 *    300 concurrent transactions with IN-list deletes, 0 with point deletes). MySQL 8.0.46 plans the same delete as a
 *    range on just the listed keys and did NOT deadlock in the same test; point deletes do not depend on the plan, so
 *    they are used on both.
 *    Like the other adapters, dedup cannot be combined with object storage (a blob may be shared).
 */
