"""Image-id format check, shared by the clients and the PostgreSQL backends.

Ids are always UUIDs generated by put(). A string that is not a UUID can never
exist, so it is treated as *not found* everywhere -- without a database round
trip, and without ever reaching a ``before_get`` hook. This matches the npm
package (``isValidId``).
"""

from __future__ import annotations

import re
import uuid

_UUID_RE = re.compile(
    r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", re.IGNORECASE
)


def is_valid_id(image_id: object) -> bool:
    """True if `image_id` is a syntactically valid UUID string (or a uuid.UUID).

    Uses ``fullmatch`` (not ``match`` with ``$``) so a trailing newline is not
    accepted. Case-insensitive, like PostgreSQL's own uuid type.
    """
    if isinstance(image_id, uuid.UUID):
        # Callers legitimately pass uuid.UUID objects (Django's <uuid:...> URL
        # converter does, and psycopg adapts them). A UUID object is valid by
        # construction.
        return True
    return isinstance(image_id, str) and _UUID_RE.fullmatch(image_id) is not None
